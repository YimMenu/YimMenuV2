// Generates src/core/translation/TranslationData.cpp from translations/ar.json.
//
// ImGui has no Arabic shaping and no bidi support, so every translation is
// converted to Arabic Presentation Forms-B and reordered into visual (LTR)
// order at build time. The game then renders the result like plain text.
//
// Usage: node tools/gen_translation_data.mjs
import fs from 'node:fs';
import path from 'node:path';
import reshaper from 'arabic-reshaper';
import bidiFactory from 'bidi-js';

const root = path.resolve(import.meta.dirname, '..');
const source = path.join(root, 'translations', 'ar.json');
const target = path.join(root, 'src', 'core', 'translation', 'TranslationData.cpp');

const bidi = bidiFactory();
const ARABIC = /[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF]/;
const PLACEHOLDER = /%(?:\d+\$)?[-+ #0]*(?:\d+|\*)?(?:\.(?:\d+|\*))?[diouxXeEfFgGaAcspn%]/g;

function shapeLine(line) {
  if (!ARABIC.test(line))
    return line;

  const placeholders = [];
  const masked = line.replace(PLACEHOLDER, (match) => `ZQ${placeholders.push(match) - 1}ZQ`);

  const shaped = reshaper.convertArabic(masked);
  const visual = bidi.getReorderedString(shaped, bidi.getEmbeddingLevels(shaped, 'rtl'));

  return visual.replace(/ZQ(\d+)ZQ/g, (_, index) => placeholders[Number(index)]);
}

function shape(text) {
  return text.split('\n').map(shapeLine).join('\n');
}

function cppString(text) {
  let out = '"';
  let afterHex = false;
  for (const byte of Buffer.from(text, 'utf8')) {
    const ch = String.fromCharCode(byte);
    if (byte < 0x80) {
      if (afterHex && /[0-9a-fA-F]/.test(ch))
        out += '""';
      afterHex = false;

      if (ch === '"') out += '\\"';
      else if (ch === '\\') out += '\\\\';
      else if (ch === '\n') out += '\\n';
      else if (ch === '\t') out += '\\t';
      else if (ch === '\r') out += '\\r';
      else out += ch;
    } else {
      out += '\\x' + byte.toString(16).toUpperCase().padStart(2, '0');
      afterHex = true;
    }
  }
  return out + '"';
}

const translations = JSON.parse(fs.readFileSync(source, 'utf8'));
const entries = Object.entries(translations);

// sanity checks
const problems = [];
const seen = new Set();
for (const [english, arabic] of entries) {
  if (seen.has(english)) problems.push(`duplicate key: ${english}`);
  seen.add(english);

  if (typeof arabic !== 'string' || arabic.length === 0) {
    problems.push(`empty translation: ${english}`);
    continue;
  }

  if (arabic.includes('##')) problems.push(`translation contains an ImGui id: ${english}`);

  const placeholders = (s) => (s.match(PLACEHOLDER) ?? []).sort().join(',');
  if (placeholders(english) !== placeholders(arabic))
    problems.push(`placeholder mismatch: ${english} -> ${arabic}`);
}

if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const lines = [];
lines.push('// Generated by tools/gen_translation_data.mjs - do not edit by hand.');
lines.push('// Source: translations/ar.json');
lines.push('#include "TranslationData.hpp"');
lines.push('');
lines.push('namespace YimMenu::Translation');
lines.push('{');
lines.push('\tnamespace');
lines.push('\t{');
lines.push('\t\tconstexpr std::pair<std::string_view, std::string_view> g_Translations[] = {');
for (const [english, arabic] of entries)
  lines.push(`\t\t    {${cppString(english)}, ${cppString(shape(arabic))}},`);
lines.push('\t\t};');
lines.push('\t}');
lines.push('');
lines.push('\tstd::span<const std::pair<std::string_view, std::string_view>> GetTranslationTable()');
lines.push('\t{');
lines.push('\t\treturn g_Translations;');
lines.push('\t}');
lines.push('}');
lines.push('');

fs.writeFileSync(target, lines.join('\n'), 'utf8');
console.log(`wrote ${entries.length} translations to ${path.relative(root, target)}`);
